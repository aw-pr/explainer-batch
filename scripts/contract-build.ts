import fs from 'fs';
import path from 'path';
import { CONTRACT_REVISION } from '../contract/explainer-v2';
import { generateSchemas } from '../contract/dialects';

const REPO_ROOT = path.resolve(__dirname, '..');
const CONTRACT_DIR = path.join(REPO_ROOT, 'contract');
const GENERATED_DIR = path.join(CONTRACT_DIR, 'generated');
const SKILL_FILE = path.join(REPO_ROOT, 'skill.md');
const SKILL_BEGIN = '<!-- CONTRACT-V2-BEGIN -->';
const SKILL_END = '<!-- CONTRACT-V2-END -->';
const VENDORED_HEADER = `// generated by explainer-batch contract:build; revision ${CONTRACT_REVISION}; do not edit`;

export interface Drift {
  file: string;
  detail: string;
}

/** The generated JSON files as they should read on disk, keyed by absolute path. */
export function renderGenerated(): Map<string, string> {
  const files = new Map<string, string>();
  for (const [name, schema] of Object.entries(generateSchemas())) {
    files.set(path.join(GENERATED_DIR, name), `${JSON.stringify(schema, null, 2)}\n`);
  }
  return files;
}

interface SkillSchema {
  type?: string | string[];
  description?: string;
  enum?: unknown[];
  properties?: Record<string, SkillSchema>;
  items?: SkillSchema;
  anyOf?: SkillSchema[];
  minItems?: number;
  maxItems?: number;
}

function schemaTypes(schema: SkillSchema): string[] {
  return schema.anyOf
    ? [...new Set(schema.anyOf.flatMap(schemaTypes))]
    : ([] as string[]).concat(schema.type ?? []);
}

function skillAnnotation(schema: SkillSchema): string {
  const parts = [schemaTypes(schema).join(' or ')];
  if (schema.enum) parts.push(`enum: ${schema.enum.map(value => JSON.stringify(value)).join(', ')}`);
  for (const bound of ['minItems', 'maxItems'] as const) {
    if (schema[bound] !== undefined) parts.push(`${bound}: ${schema[bound]}`);
  }
  if (schema.description) parts.push(schema.description);
  return parts.filter(Boolean).join('; ');
}

function renderSkillNode(schema: SkillSchema, prefix: string, depth: number, suffix = ''): string[] {
  const indent = '  '.repeat(depth);
  const annotation = ` // ${skillAnnotation(schema)}`;
  if (schema.anyOf) {
    return [
      `${indent}${prefix}(${annotation}`,
      ...schema.anyOf.flatMap((branch, i) =>
        renderSkillNode(branch, '', depth + 1, i < schema.anyOf!.length - 1 ? ' or' : '')),
      `${indent})${suffix}`,
    ];
  }
  if (schema.properties) {
    const properties = Object.entries(schema.properties);
    return [
      `${indent}${prefix}{${annotation}`,
      ...properties.flatMap(([key, child], i) =>
        renderSkillNode(child, `${JSON.stringify(key)}: `, depth + 1, i < properties.length - 1 ? ',' : '')),
      `${indent}}${suffix}`,
    ];
  }
  if (schema.items) {
    return [
      `${indent}${prefix}[${annotation}`,
      ...renderSkillNode(schema.items, '', depth + 1),
      `${indent}]${suffix}`,
    ];
  }
  const value = schema.enum?.map(value => JSON.stringify(value)).join(' | ')
    ?? schemaTypes(schema).join(' or ');
  return [`${indent}${prefix}${value}${suffix}${annotation}`];
}

/** The annotated wire skeleton, with no filesystem or marker dependencies. */
export function renderSkillBlock(): string {
  const schema = generateSchemas()['model-output.openai.json'] as SkillSchema;
  return `\n\`\`\`\n${renderSkillNode(schema, '', 0).join('\n')}\n\`\`\`\n`;
}

export function renderSkill(current: string): string {
  for (const marker of [SKILL_BEGIN, SKILL_END]) {
    if (current.split(marker).length !== 2) throw new Error(`skill.md needs exactly one ${marker}`);
  }
  const begin = current.indexOf(SKILL_BEGIN) + SKILL_BEGIN.length;
  const end = current.indexOf(SKILL_END);
  if (begin > end) throw new Error(`skill.md needs ${SKILL_BEGIN} before ${SKILL_END}`);
  return current.slice(0, begin) + renderSkillBlock() + current.slice(end);
}

function renderSkillFile(): Map<string, string> {
  return new Map([[SKILL_FILE, renderSkill(fs.readFileSync(SKILL_FILE, 'utf8'))]]);
}

/** Every contract/*.ts source as promo-flow should vendor it, keyed by absolute path. */
export function renderVendored(websiteRepo: string): Map<string, string> {
  const files = new Map<string, string>();
  const sources = fs.readdirSync(CONTRACT_DIR).filter((f) => f.endsWith('.ts')).sort();
  for (const name of sources) {
    const source = fs.readFileSync(path.join(CONTRACT_DIR, name), 'utf8');
    files.set(path.join(websiteRepo, 'src', 'contract', name), `${VENDORED_HEADER}\n${source}`);
  }
  return files;
}

function firstDifference(expected: string, actual: string): string {
  const want = expected.split('\n');
  const have = actual.split('\n');
  for (let i = 0; i < Math.max(want.length, have.length); i++) {
    if (want[i] !== have[i]) {
      return `line ${i + 1}: expected ${JSON.stringify(want[i] ?? '<end of file>')}, found ${JSON.stringify(have[i] ?? '<end of file>')}`;
    }
  }
  return 'contents differ';
}

function compare(files: Map<string, string>): Drift[] {
  const drift: Drift[] = [];
  for (const [file, expected] of files) {
    if (!fs.existsSync(file)) {
      drift.push({ file, detail: 'missing' });
      continue;
    }
    const actual = fs.readFileSync(file, 'utf8');
    if (actual !== expected) drift.push({ file, detail: firstDifference(expected, actual) });
  }
  return drift;
}

/**
 * Renders everything contract:build writes into memory and compares it with
 * disk: the generated JSON and skill block always, and promo-flow's vendored
 * copies when a website repo is given. An empty result means up to date.
 */
export function checkContract(options: { websiteRepo?: string } = {}): Drift[] {
  const drift = compare(renderGenerated());
  drift.push(...compare(renderSkillFile()));
  if (options.websiteRepo) drift.push(...compare(renderVendored(options.websiteRepo)));
  return drift;
}

function writeIfChanged(files: Map<string, string>): string[] {
  const written: string[] = [];
  for (const [file, content] of files) {
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) continue;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    written.push(file);
  }
  return written;
}

function relative(file: string): string {
  return path.relative(REPO_ROOT, file) || file;
}

function main(argv: string[]): number {
  const check = argv.includes('--check');
  const websiteRepo = process.env.WEBSITE_REPO?.trim() || undefined;

  if (argv.includes('--website') && !websiteRepo) {
    console.error('contract: --website needs WEBSITE_REPO set to the promo-flow checkout');
    return 2;
  }
  if (websiteRepo && !fs.statSync(websiteRepo, { throwIfNoEntry: false })?.isDirectory()) {
    console.error(`contract: WEBSITE_REPO is not a directory: ${websiteRepo}`);
    return 2;
  }

  if (check) {
    const drift = checkContract({ websiteRepo });
    if (drift.length === 0) {
      console.log('contract: generated files up to date');
      return 0;
    }
    for (const d of drift) console.error(`contract: drifted ${relative(d.file)} (${d.detail})`);
    console.error('contract: run npm run contract:build to regenerate');
    return 1;
  }

  const written = writeIfChanged(renderGenerated());
  written.push(...writeIfChanged(renderSkillFile()));
  if (websiteRepo) written.push(...writeIfChanged(renderVendored(websiteRepo)));
  for (const file of written) console.log(`contract: wrote ${relative(file)}`);
  if (written.length === 0) console.log('contract: generated files up to date');
  return 0;
}

if (require.main === module) {
  process.exitCode = main(process.argv.slice(2));
}
