import crypto from 'crypto';
import fs from 'fs';
import path from 'path';

const PROVIDERS = ['claude', 'openai', 'gemini'] as const;
type Provider = (typeof PROVIDERS)[number];

// Reviewed table: the fleet file names no provider, route or modality per model.
const PROVIDER_BY_PREFIX: Array<[string, Provider]> = [
  ['claude-', 'claude'],
  ['gpt-', 'openai'],
  ['gemini-', 'gemini'],
];
const ROUTES_BY_PROVIDER: Record<Provider, string[]> = {
  claude: ['batch-api', 'subscription-cli', 'sync-api'],
  openai: ['batch-api', 'subscription-cli', 'sync-api'],
  gemini: ['batch-api', 'sync-api'],
};

type Json = Record<string, unknown>;

function isRecord(value: unknown): value is Json {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function sortedEntries<T>(record: Record<string, T>): Array<[string, T]> {
  return Object.entries(record).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

function sortedObject<T>(record: Record<string, T>): Record<string, T> {
  return Object.fromEntries(sortedEntries(record));
}

function argValue(flag: string): string | undefined {
  const index = process.argv.indexOf(flag);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

function fail(message: string): never {
  console.error(`update-model-snapshot: ${message}`);
  process.exit(1);
}

function main(): void {
  const fleetArg = argValue('--fleet') ?? process.env.MCP_MODEL_REGISTRY;
  if (!fleetArg) fail('pass --fleet <file> or set MCP_MODEL_REGISTRY.');
  const out = path.resolve(argValue('--out') ?? path.join(__dirname, '..', 'config', 'models.snapshot.json'));

  const bytes = fs.readFileSync(path.resolve(fleetArg));
  const fleet: unknown = JSON.parse(bytes.toString('utf-8'));
  if (!isRecord(fleet)) fail('fleet file is not a JSON object.');

  const tiers: Record<string, Record<string, string>> = {};
  const providerOf = new Map<string, Provider>();
  for (const provider of PROVIDERS) {
    const tierObject = fleet[provider];
    if (!isRecord(tierObject)) continue;
    const aliases: Record<string, string> = {};
    for (const [alias, id] of Object.entries(tierObject)) {
      if (typeof id !== 'string') continue;
      aliases[alias] = id;
      if (!providerOf.has(id)) providerOf.set(id, provider);
    }
    tiers[provider] = sortedObject(aliases);
  }

  const pricing: Record<string, Json> = {};
  if (isRecord(fleet.pricing)) {
    for (const [id, row] of Object.entries(fleet.pricing)) {
      if (id.startsWith('_') || !isRecord(row)) continue;
      pricing[id] = sortedObject(row);
      if (!providerOf.has(id)) {
        const match = PROVIDER_BY_PREFIX.find(([prefix]) => id.startsWith(prefix));
        if (!match) fail(`no reviewed provider for priced model "${id}"; extend the table in this script.`);
        providerOf.set(id, match[1]);
      }
    }
  }

  const models: Record<string, Json> = {};
  for (const [id, provider] of providerOf) {
    models[id] = { images: true, pdf: true, provider, routes: ROUTES_BY_PROVIDER[provider] };
  }

  const snapshot = {
    _comment: 'Generated by scripts/update-model-snapshot.ts from the fleet model registry. Do not edit by hand.',
    currency: 'USD',
    source: {
      sha256: crypto.createHash('sha256').update(bytes).digest('hex'),
      updated: typeof fleet._updated === 'string' ? fleet._updated : null,
    },
    ...tiers,
    models: sortedObject(models),
    pricing: sortedObject(pricing),
  };

  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, `${JSON.stringify(snapshot, null, 2)}\n`);
}

main();
