test('the OpenAI dialect is strict: closed objects, every property required, no unsupported keywords', () => {
  const schema = readDialect('model-output.openai.json');
  assert.deepEqual([...(schema.required ?? [])].sort(), [...WIRE_KEYS].sort(), 'the root requires exactly the seven wire keys');
  const objects = nodes(schema).filter((n) => n.properties);
  assert.ok(objects.length >= 10, 'the OpenAI dialect must describe the nested objects');
  for (const n of objects) {
    assert.equal(n.additionalProperties, false, `object with ${Object.keys(n.properties).join(',')} must set additionalProperties false`);
    assert.deepEqual([...(n.required ?? [])].sort(), Object.keys(n.properties).sort(), `object with ${Object.keys(n.properties).join(',')} must require every property`);
  }
  const text = JSON.stringify(schema);
  for (const kw of ['"$schema"', '"const"', '"oneOf"', '"minLength"', '"maxLength"']) {
    assert.ok(!text.includes(kw), `the OpenAI dialect must not contain ${kw}`);
  }
  assert.ok([].concat(schema.properties.figure_request.type).includes('null'), 'figure_request is nullable as type [object, null]');
  assert.equal(schema.properties.charts.maxItems, 1, 'charts carries maxItems 1');
  assert.equal(schema.properties.top_block.anyOf?.length, 2, 'top_block is an anyOf of the pills and takeaway variants');
});

