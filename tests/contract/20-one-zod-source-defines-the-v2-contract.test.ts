function nodes(schema: unknown): Record<string, any>[] {
  const out: Record<string, any>[] = [];
  const visit = (n: unknown): void => {
    if (Array.isArray(n)) { n.forEach(visit); return; }
    if (n && typeof n === 'object') {
      out.push(n as Record<string, any>);
      for (const [k, v] of Object.entries(n)) {
        if (k === 'properties' && v && typeof v === 'object') Object.values(v).forEach(visit);
        else visit(v);
      }
    }
  };
  visit(schema);
  return out;
}

