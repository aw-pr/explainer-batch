test('contract:build --website vendors every contract source and leaves skill.md and the generated files alone', () => {
  const website = path.join(TMP, 'promo-flow');
  fs.mkdirSync(path.join(website, 'src'), { recursive: true });
  const skillBefore = sha(path.join(REPO_ROOT, 'skill.md'));
  const genBefore = DIALECTS.map((f) => sha(path.join(GEN, f)));
  const r = npm(['contract:build', '--', '--website'], { WEBSITE_REPO: website });
  assert.equal(r.status, 0, r.out);
  const sources = fs.readdirSync(path.join(REPO_ROOT, 'contract')).filter((f) => f.endsWith('.ts'));
  for (const f of ['explainer-v2.ts', 'inline.ts', 'derive.ts', 'dialects.ts']) assert.ok(sources.includes(f), `contract/${f} must exist`);
  for (const f of sources) {
    const copy = path.join(website, 'src', 'contract', f);
    assert.ok(fs.existsSync(copy), `contract:build --website must write src/contract/${f}`);
    const [first, ...rest] = fs.readFileSync(copy, 'utf8').split('\n');
    assert.equal(first, HEADER);
    assert.equal(rest.join('\n'), fs.readFileSync(path.join(REPO_ROOT, 'contract', f), 'utf8'), `src/contract/${f} must be a verbatim copy after the header`);
  }
  assert.equal(sha(path.join(REPO_ROOT, 'skill.md')), skillBefore, 'contract:build must not touch skill.md before W5 adds the markers');
  assert.deepEqual(DIALECTS.map((f) => sha(path.join(GEN, f))), genBefore, 'a build on an up-to-date tree must leave the generated files byte-identical');
  const vendoredOk = npm(['contract:check'], { WEBSITE_REPO: website });
  assert.equal(vendoredOk.status, 0, `contract:check with WEBSITE_REPO must pass on fresh copies: ${vendoredOk.out}`);
  const copy = path.join(website, 'src', 'contract', 'inline.ts');
  fs.appendFileSync(copy, '// hand edit\n');
  const vendoredDrift = npm(['contract:check'], { WEBSITE_REPO: website });
  assert.equal(vendoredDrift.status, 1, 'contract:check with WEBSITE_REPO must exit 1 when a vendored copy drifts');
  assert.match(vendoredDrift.out, /inline\.ts/, 'contract:check must name the drifted vendored copy');
  const noTarget = npm(['contract:build', '--', '--website'], { WEBSITE_REPO: '' });
  assert.notEqual(noTarget.status, 0, '--website with no WEBSITE_REPO must fail rather than write somewhere unexpected');
  assert.match(noTarget.out, /WEBSITE_REPO/, 'the failure must name WEBSITE_REPO');
});

